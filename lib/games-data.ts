// lib/games-data.ts
// Games database — expand this over time. More games = more rankable pages.
// Each game generates: /games/[slug], /fps/[gameId]/[cpuId]/[gpuId] (CPUs × GPUs × games)

export interface Game {
  id: string
  name: string
  genre: string
  releaseYear: number
  publisher: string
  // FPS at REFERENCE BUILD (cpuScore=75, gpuScore=75) — medium-high settings
  baseFps: {
    '1080p': number
    '1440p': number
    '4k': number
  }
  // 0 = fully CPU-bound, 1 = fully GPU-bound
  // Higher res shifts every game toward GPU
  gpuBound: number
  requirements: {
    minimum:     { cpuScore: number; gpuScore: number; ramGb: number }
    recommended: { cpuScore: number; gpuScore: number; ramGb: number }
    ultra:       { cpuScore: number; gpuScore: number; ramGb: number }
  }
  tags: string[]
  isCompetitive: boolean // esports titles — players prioritize high FPS
  hasRayTracing: boolean
  apiSupport: ('DirectX 11' | 'DirectX 12' | 'Vulkan' | 'OpenGL')[]
}

