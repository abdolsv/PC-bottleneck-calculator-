// Helper: get game by id
export function getGameById(id: string): Game | undefined {
  return GAMES.find(g => g.id === id)
}

// Helper: get games by genre
export function getGamesByGenre(genre: string): Game[] {
  return GAMES.filter(g => g.genre.toLowerCase().includes(genre.toLowerCase()))
}

// Helper: get games by tag
export function getGamesByTag(tag: string): Game[] {
  return GAMES.filter(g => g.tags.includes(tag))
}

// Competitive / esports focused games
export const COMPETITIVE_GAMES = GAMES.filter(g => g.isCompetitive)

// Demanding AAA games
export const DEMANDING_GAMES = GAMES.filter(g =>
  g.requirements.recommended.gpuScore >= 65
)
